// Helper function to get data for a specific slug
export function getOffshoreDeveloperData(slug: string) {
  const data = offshoreDeveloperData[slug];

  if (!data) {
    // Fallback for unknown slugs
    const formattedName = slug
      .split("-")
      .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
      .join(" ");

    return {
      title: `Hire ${formattedName} Developers <br /> Partner With Top-Rated ${formattedName} Programmers`,
      description: `Hire expert ${formattedName} developers for your project needs. Our dedicated ${formattedName} programmers deliver high-quality, scalable solutions with cutting-edge technology and industry best practices.`,
    };
  }

  return data;
}

export function getoffshoreDeveloperData(slug: string) {
  return (
    offshoreDeveloperData[slug] || {
      title: `Hire ${formatSlug(slug)} Developers <br /> Partner With Top-Rated ${formatSlug(slug)} Programmers`,
      description: `Hire expert ${formatSlug(slug)} developers for your project needs. Our dedicated ${formatSlug(slug)} programmers deliver high-quality, scalable solutions with cutting-edge technology.`,
    }
  );
}

function formatSlug(slug: string): string {
  return slug
    .split("-")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
}
